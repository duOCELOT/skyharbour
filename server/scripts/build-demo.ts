// Bundles the offline demo harbour (src/demo/browser.ts) for static hosting:
// client/demo/demo.js + the sql.js wasm beside it. Commit the output — the
// GitHub Pages build serves the repo as-is, with no build step.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
const server = path.resolve(here, '..');
const outDir = path.resolve(server, '../client/demo');
const shim = (f: string) => path.join(server, 'src/demo/shims', f);

await build({
  entryPoints: [path.join(server, 'src/demo/browser.ts')],
  outfile: path.join(outDir, 'demo.js'),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  alias: { 'node:crypto': shim('crypto.ts'), crypto: shim('empty.ts'), fs: shim('empty.ts'), path: shim('empty.ts') },
  banner: { js: '// GENERATED by server/scripts/build-demo.ts — do not edit; run `npm run build:demo`.' },
});
fs.copyFileSync(path.join(server, 'node_modules/sql.js/dist/sql-wasm.wasm'), path.join(outDir, 'sql-wasm.wasm'));
console.log('demo bundle →', path.relative(process.cwd(), outDir));
